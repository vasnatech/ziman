#!/usr/bin/env python3
"""Generates src/regex_unicode.h: code point ranges for the Unicode general
categories (\\p{L}, \\p{Lu}, ...) from Python's unicodedata, plus a few scripts
approximated by their main blocks. Run: python3 tools/gen_regex_unicode.py > src/regex_unicode.h"""
import sys
import unicodedata

def ranges_for(pred):
    out = []
    start = None
    prev = None
    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF:
            hit = False
        else:
            hit = pred(cp)
        if hit:
            if start is None:
                start = cp
            prev = cp
        elif start is not None:
            out.append((start, prev))
            start = None
    if start is not None:
        out.append((start, prev))
    return out

cats = {}
def cat(cp):
    return unicodedata.category(chr(cp))

two = ["Lu", "Ll", "Lt", "Lm", "Lo", "Mn", "Mc", "Me", "Nd", "Nl", "No", "Pc", "Pd", "Ps", "Pe", "Pi", "Pf", "Po",
       "Sm", "Sc", "Sk", "So", "Zs", "Zl", "Zp", "Cc", "Cf"]
one = ["L", "M", "N", "P", "S", "Z"]
tables = {}
for c in two:
    tables[c] = ranges_for(lambda cp, c=c: cat(cp) == c)
for c in one:
    tables[c] = ranges_for(lambda cp, c=c: cat(cp).startswith(c))
tables["C"] = ranges_for(lambda cp: cat(cp) in ("Cc", "Cf"))

# scripts, approximated by their main Unicode blocks
scripts = {
    "Latin": [(0x41, 0x5A), (0x61, 0x7A), (0xAA, 0xAA), (0xBA, 0xBA), (0xC0, 0xD6), (0xD8, 0xF6), (0xF8, 0x2B8), (0x1E00, 0x1EFF), (0x2C60, 0x2C7F), (0xA720, 0xA7FF), (0xFF21, 0xFF3A), (0xFF41, 0xFF5A)],
    "Greek": [(0x370, 0x3FF), (0x1F00, 0x1FFF)],
    "Cyrillic": [(0x400, 0x52F), (0x1C80, 0x1C8F), (0x2DE0, 0x2DFF), (0xA640, 0xA69F)],
    "Armenian": [(0x531, 0x58F)],
    "Hebrew": [(0x591, 0x5F4)],
    "Arabic": [(0x600, 0x6FF), (0x750, 0x77F), (0x8A0, 0x8FF), (0xFB50, 0xFDFF), (0xFE70, 0xFEFF)],
    "Devanagari": [(0x900, 0x97F)],
    "Thai": [(0xE01, 0xE5B)],
    "Hiragana": [(0x3041, 0x309F)],
    "Katakana": [(0x30A0, 0x30FF), (0x31F0, 0x31FF), (0xFF66, 0xFF9F)],
    "Hangul": [(0x1100, 0x11FF), (0x3130, 0x318F), (0xAC00, 0xD7AF)],
    "Han": [(0x2E80, 0x2FDF), (0x3005, 0x3007), (0x3021, 0x3029), (0x3400, 0x4DBF), (0x4E00, 0x9FFF), (0xF900, 0xFAFF), (0x20000, 0x2FA1F)],
}

print("/* Generated by tools/gen_regex_unicode.py from Unicode %s -- do not edit. */" % unicodedata.unidata_version)
print("#ifndef ZIMAN_REGEX_UNICODE_H\n#define ZIMAN_REGEX_UNICODE_H\n")
print("#include <stdint.h>\n")
print("typedef struct { const char *name; const uint32_t (*ranges)[2]; int count; } UnicodeSet;\n")
entries = []
def emit(name, rs):
    print("static const uint32_t UNI_%s[][2] = {" % name)
    line = "   "
    for lo, hi in rs:
        item = " {0x%X,0x%X}," % (lo, hi)
        if len(line) + len(item) > 110:
            print(line)
            line = "   "
        line += item
    print(line + "\n};")
    entries.append((name, len(rs)))
for name in one + ["C"] + two:
    emit(name, tables[name])
for name, rs in scripts.items():
    emit(name, rs)
print("\nstatic const UnicodeSet UNICODE_SETS[] = {")
for name, n in entries:
    print('    {"%s", UNI_%s, %d},' % (name, name, n))
print("};\n\n#define UNICODE_SET_COUNT %d\n\n#endif" % len(entries))
