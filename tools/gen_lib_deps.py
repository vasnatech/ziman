#!/usr/bin/env python3
"""Generates docs/lib/dependencies.md: which bundled module `use`s which, as a Mermaid diagram and a table.

Read from the `use` lines of every module under lib/, so it cannot drift from the code; regenerate with
`make corelib-reference`. A module that names another (`use json`, `use json.Json`) depends on it. The
prelude is in every program and is left out.
"""
import collections
import glob
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
# Keyed by the first path component under lib/, which is the group a module is filed in.
# `graphics` and `ui` were missing, so every module in either was drawn as a bare node outside
# any subgraph and labelled without its folder -- which the prose above promises.
FOLDERS = {
    "core": "core",
    "db": "databases",
    "graphics": "graphics",
    "http": "HTTP",
    "time": "time",
    "ui": "user interface",
}

# **Which folders hold parts and which hold modules is in the Makefile, not in the names.**
# "a folder whose name matches a file inside it" looked like a sound test for a multi-part module
# and is not: `lib/ui/desktop/` holds `desktop.zm` *and* `window.zm`, `ibus.zm` and `atspi.zm`,
# which are four separate bundled modules -- `CORELIB_MODULES` lists all four. Under the old test
# three of them vanished from this map, `window` among them, on a page that says it is read from
# every module under `lib/` and cannot drift. The `*_PARTS` tables are the real answer, and they
# are keyed by folder *and* part because `metrics` is both a part of `server` and a core module.
PARTS = set()
with open(os.path.join(ROOT, "Makefile")) as f:
    for line in f:
        m = re.match(r"([A-Z]+)_PARTS := (.+)", line)
        if m and m.group(1) != "PRELUDE":
            names = m.group(2).split()
            for part in names[1:]:
                PARTS.add((names[0], part))

mods = {}
for path in glob.glob(os.path.join(ROOT, "lib", "*", "*.zm")):
    folder = os.path.basename(os.path.dirname(path))
    # lib/prelude/ is not a folder of modules: its files are merged bare into every program and
    # nothing can `use` one, so a dependency graph has nothing to say about them. They only became
    # visible here when the prelude stopped being a single lib/prelude.zm, which this glob missed
    # by shape rather than on purpose -- hence the explicit skip now.
    if folder == "prelude":
        continue
    mods[os.path.basename(path)[:-3]] = folder

# **The multi-part modules, which this missed entirely until 2026-11-01.** `server`, `client` and
# `rest` are folders of parts one level deeper (`lib/http/server/read.zm`), so `lib/*/*.zm` never
# saw them -- and the prose above names `http.server` as though it were on the map. A part folder
# is one whose name matches a file inside it (`lib/http/server/server.zm`), which is the same shape
# `src/corelib.c`'s MODULE_PARTS and the Makefile's `<NAME>_PARTS` already encode; the first part
# carries the imports, so that is the file to read.
for path in glob.glob(os.path.join(ROOT, "lib", "*", "*", "*.zm")):
    folder = os.path.basename(os.path.dirname(path))
    group = os.path.basename(os.path.dirname(os.path.dirname(path)))
    name = os.path.basename(path)[:-3]
    if group == "prelude" or (folder, name) in PARTS:
        continue
    mods[name] = os.path.join(group, folder)

deps = collections.defaultdict(set)
for name in mods:
    with open(os.path.join(ROOT, "lib", mods[name], name + ".zm")) as f:
        for line in f:
            # **Digits included**: `[a-z_]+` matched `a` of `use a11y` and then failed the
            # `in mods` test, so the one module with a digit in its name had no arrows on this
            # map at all -- `atspi` uses it.
            m = re.match(r"use ([a-z0-9_]+)", line)
            if m and m.group(1) in mods and m.group(1) != name:
                deps[name].add(m.group(1))

used_by = collections.defaultdict(set)
for name, ds in deps.items():
    for d in ds:
        used_by[d].add(name)

# level 0: needs nothing; otherwise one more than the deepest thing it needs
level = {}
def depth(name, seen=()):
    if name in level:
        return level[name]
    level[name] = 0 if not deps[name] else 1 + max(depth(d) for d in deps[name])
    return level[name]
for name in mods:
    depth(name)

out = ["# Library dependencies", "",
       "Which bundled module `use`s which, read from the `use` lines under `lib/` (generated by",
       "`tools/gen_lib_deps.py`; `make corelib-reference` regenerates it). An arrow runs from a module to one it",
       "uses. Boxes are named by module, with the folder in front when it is not `core` (`http.server`, `db.pg`); a program writes just the module (`use server`). The prelude is in every program and is left out; a module with no arrows uses only the prelude",
       "and its own natives.", "",
       "```mermaid", "flowchart LR"]
def group_of(name):
    return mods[name].split(os.sep)[0]

for folder, title in FOLDERS.items():
    members = sorted(n for n in mods if group_of(n) == folder)
    out.append('    subgraph group_%s["%s"]' % (folder, title))
    for n in members:
        out.append('        %s["%s"]' % (n, n if folder == "core" or n == folder else "%s.%s" % (folder, n)))
    out.append("    end")
for name in sorted(mods):
    for d in sorted(deps[name]):
        out.append("    %s --> %s" % (name, d))
out += ["```", "",
        "## By layer", "",
        "A module is on layer 0 when it uses no other module, and one more than the deepest module it uses",
        "otherwise: everything on a layer depends only on lower layers.", "",
        "| Layer | Modules |", "|---|---|"]
layers = collections.defaultdict(list)
for name, l in level.items():
    layers[l].append(name)
for l in sorted(layers):
    out.append("| %d | %s |" % (l, ", ".join("`%s`" % n for n in sorted(layers[l]))))
out += ["", "## Each module", "", "| Module | Uses | Used by |", "|---|---|---|"]
def cell(names):
    return ", ".join("`%s`" % n for n in sorted(names)) or "-"
for name in sorted(mods):
    out.append("| `%s` | %s | %s |" % (name, cell(deps[name]), cell(used_by[name])))
out += ["", "## Why some modules are separate", "",
        "- `db` holds what the database modules share (`SqlValue`, `Row`, `DbError`, the URL parser) so that `pg`,",
        "  `mysql`, `sqlite`, `time` and `uuid` can use it without using `datasource`, which uses them.",
        "- `http` holds what `server` and `client` share (`Request`, `Response`, `Header`, `HttpMethod`) so neither",
        "  needs the other.",
        "- `zone` reads the operating system's zone files for `time`; it needs only `fs`, `number` and `os`.", ""]
with open(os.path.join(ROOT, "docs", "lib", "dependencies.md"), "w") as f:
    f.write("\n".join(out))
