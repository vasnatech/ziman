#!/usr/bin/env python3
"""Regenerates the design journal's index -- docs/design/journal/README.md, between its two
marker comments -- from the entries in the journal's part files.

The journal is a dated decision log of 200-plus entries, which makes it hard to see that a topic is
covered twice -- and when it is, the later entry is usually the current answer while the earlier one
records how it started. That is F11's hazard: a reader who stops at the first hit gets the state of
an earlier version. An index does not fix that on its own, but it is what makes the second entry
visible at all.

Generated rather than hand-kept for the reason every other generated page here is: a hand-written
index of this much text is wrong within a month. `make design-index-check` fails when the committed
index is not what this script produces, the same way `lib-manual-check` guards docs/lib.

**It indexes a folder rather than one file since 2026-10-30.** docs/design/journal/ had reached 10,449
lines and 1.2 MB -- more than fits in one context window, so neither a person nor a model could read
it in a pass, and two documentation errors came out of reading around it instead of through it. The
entries now live in fortnightly parts plus `principles.md` and `v0-decisions.md`, and a link here
carries the file as well as the anchor. The parts are discovered rather than listed, so a new
fortnight needs no edit to this script; they sort by name, which is why a part is named for the
first date it covers.

Anchors follow GitHub's own rule -- lowercase, punctuation dropped, spaces to hyphens -- so the links
work in the rendered files and in any viewer that follows them.
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
JOURNAL = os.path.join(ROOT, "docs", "design", "journal")
DOC = os.path.join(JOURNAL, "README.md")
START = "<!-- index: generated by tools/gen_design_index.py -- run `make design-index` -->"
END = "<!-- end index -->"

# The two parts that are not a fortnight, in the order they should be read: the principles the
# language is argued from, then the v0 decisions those produced. Everything else is dated and sorts
# into place after them.
LEADING = ["principles.md", "v0-decisions.md"]


def anchor(title):
    """GitHub's heading anchor: lowercased, anything but a letter, digit, space, hyphen or
    underscore dropped, then spaces to hyphens."""
    a = title.lower()
    a = re.sub(r"[^\w\s-]", "", a, flags=re.UNICODE)
    return re.sub(r"\s+", "-", a.strip())


def parts():
    """The journal's part files, reading order: the two named ones, then the dated ones by name."""
    found = [f for f in os.listdir(JOURNAL) if f.endswith(".md") and f != "README.md"]
    dated = sorted(f for f in found if f not in LEADING)
    missing = [f for f in LEADING if f not in found]
    if missing:
        print(f"gen_design_index.py: {JOURNAL} is missing {', '.join(missing)}", file=sys.stderr)
        sys.exit(1)
    return LEADING + dated


def main():
    body = []
    count = 0
    for part in parts():
        # An anchor is unique per file, so the -1/-2 suffixing GitHub does for a repeated heading
        # is counted per file too -- not across the journal, as it was while this was one document.
        seen = {}
        for line in open(os.path.join(JOURNAL, part)):
            if not line.startswith("## "):
                continue
            title = line[3:].strip()
            a = anchor(title)
            seen[a] = seen.get(a, -1) + 1
            if seen[a]:
                a = f"{a}-{seen[a]}"
            body.append(f"- [{title}]({part}#{a})")
            count += 1
    lines = open(DOC).read().split("\n")
    if START not in lines or END not in lines:
        print(f"gen_design_index.py: {DOC} has no index markers; add {START} / {END}", file=sys.stderr)
        return 1
    out = lines[: lines.index(START) + 1] + [""] + body + [""] + lines[lines.index(END):]
    open(DOC, "w").write("\n".join(out))
    print(f"gen_design_index.py: {count} entries indexed across {len(parts())} parts")
    return 0


if __name__ == "__main__":
    sys.exit(main())
