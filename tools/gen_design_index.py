#!/usr/bin/env python3
"""Regenerates docs/DESIGN.md's index of sections, in place, between its two marker comments.

DESIGN.md is a dated decision log of 100-plus sections and 5,000-plus lines, which makes it hard to
see that a topic is covered twice -- and when it is, the later entry is usually the current answer
while the earlier one records how it started. That is F11's hazard: a reader who stops at the first
hit gets the state of an earlier version. An index does not fix that on its own, but it is what makes
the second entry visible at all.

Generated rather than hand-kept for the reason every other generated page here is: a hand-written
index of a file this size is wrong within a month. `make design-index-check` fails when the committed
index is not what this script produces, the same way `lib-manual-check` guards docs/lib.

Anchors follow GitHub's own rule -- lowercase, punctuation dropped, spaces to hyphens -- so the links
work in the rendered file and in any viewer that follows it.
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DOC = os.path.join(ROOT, "docs", "DESIGN.md")
START = "<!-- index: generated by tools/gen_design_index.py -- run `make design-index` -->"
END = "<!-- end index -->"


def anchor(title):
    """GitHub's heading anchor: lowercased, anything but a letter, digit, space, hyphen or
    underscore dropped, then spaces to hyphens."""
    a = title.lower()
    a = re.sub(r"[^\w\s-]", "", a, flags=re.UNICODE)
    return re.sub(r"\s+", "-", a.strip())


def main():
    lines = open(DOC).read().split("\n")
    if START not in lines or END not in lines:
        print(f"gen_design_index.py: {DOC} has no index markers; add {START} / {END}", file=sys.stderr)
        return 1
    seen = {}
    body = []
    for line in lines:
        if not line.startswith("## "):
            continue
        title = line[3:].strip()
        # The front matter is not an entry: "How to read this file" and "Index" itself.
        if title in ("How to read this file", "Index"):
            continue
        a = anchor(title)
        # GitHub suffixes a repeated anchor with -1, -2, ...; mirror that so duplicates still link.
        seen[a] = seen.get(a, -1) + 1
        if seen[a]:
            a = f"{a}-{seen[a]}"
        body.append(f"- [{title}](#{a})")
    out = lines[: lines.index(START) + 1] + [""] + body + [""] + lines[lines.index(END):]
    open(DOC, "w").write("\n".join(out))
    print(f"gen_design_index.py: {len(body)} sections indexed")
    return 0


if __name__ == "__main__":
    sys.exit(main())
