#!/usr/bin/env python3
"""Runs `ziman --lint` over every module in lib/, and over the prelude.

**One pass, since 2026-10-31.** It used to be two, and the first was a workaround: a bundled
module's declarations carry a NULL `source_file` -- the very flag the lint uses to tell a user's
code from the standard library -- so every finding in `lib/` was discarded before it was printed
(docs/reviews/tasks/ F133). The way round it was to generate a throwaway entry importing every
module and point `ZIMAN_MODULE_PATH` at the sources, so they loaded *from disk* with real paths;
the prelude, which cannot be imported at all, needed `--lint-bundled` separately.

That stopped working when `server` and `client` became folders of parts: from disk, `use server`
resolves to `lib/http/server/server.zm` alone, and the nine names the other parts hold are then
undefined. Rather than teach this tool the exception, every bundled module now carries its own
`origin_file` (src/loader.c, from the path the Makefile embeds beside the source), which is what
`--lint-bundled` reports against -- so one carrier program that imports everything lints all of
`lib/`, parts and prelude included, with real file names and no module path to set.

**`// lint-ok: <reason>`** on the line a finding points at drops it, the same shape and for the
same purpose as `/* xalloc-ok: ... */` in the C (tools/check_xalloc.py): some accumulations really
are bounded, and the alternative to recording that in the source is leaving this ungated for ever.
The reason is required -- a bare marker is refused -- because the reason is the whole value of it.

Exits 1 if any finding survives, 0 otherwise.
"""
import glob
import os
import re
import subprocess
import sys
import tempfile

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
FINDING = re.compile(r"^(?P<file>[^:]+):(?P<line>\d+):(?P<col>\d+): warning: (?P<msg>.*)$")


def bundled_modules(ziman):
    """Every bundled module, from the compiler itself rather than from a list kept here.

    `ziman --api` with no module named prints them, which is the same table `use` resolves
    against -- so a module added to the binary is linted without touching this file."""
    done = subprocess.run([ziman, "--api"], capture_output=True, text=True)
    # Two-space-indented single words. The listing ends with `  builtins   the functions that need
    # no 'use' at all`, which is prose about a pseudo-module rather than a row, so a row is a line
    # whose whole content is one name.
    names = [l.strip() for l in done.stdout.splitlines()
             if l.startswith("  ") and re.fullmatch(r"[a-z_0-9]+", l.strip())]
    if not names:
        sys.exit("lint_lib.py: 'ziman --api' listed no bundled modules -- it was reshaped, and "
                 "this tool reads it rather than keeping its own copy")
    return names


def suppressed(finding):
    """True when the line a finding points at carries `// lint-ok: <reason>`."""
    m = FINDING.match(finding)
    if m is None:
        return False
    try:
        with open(m.group("file")) as f:
            line = f.read().splitlines()[int(m.group("line")) - 1]
    except (OSError, IndexError):
        return False
    marker = "// lint-ok:"
    at = line.find(marker)
    if at < 0:
        return False
    if not line[at + len(marker):].strip():
        print("lint_lib.py: %s:%s has a bare `// lint-ok:` -- give the reason, it is the point of "
              "the marker" % (m.group("file"), m.group("line")), file=sys.stderr)
        return False
    return True


def main():
    ziman = os.path.join(ROOT, "ziman")
    modules = bundled_modules(ziman)
    carrier = ["// Generated by tools/lint_lib.py -- every bundled module, so --lint-bundled loads",
               "// them all. The prelude needs no `use`: it is merged into every program."]
    carrier += ["use %s" % m for m in modules]
    carrier += ["", "fn main() {", '    print("lint")', "}"]
    with tempfile.TemporaryDirectory() as tmp:
        path = os.path.join(tmp, "lint_all.zm")
        with open(path, "w") as f:
            f.write("\n".join(carrier) + "\n")
        done = subprocess.run([ziman, "--lint-bundled", path], capture_output=True, text=True)

    findings = [l for l in (done.stdout + done.stderr).strip().splitlines() if l]
    kept = [f for f in findings if not suppressed(f)]
    files = len(glob.glob(os.path.join(ROOT, "lib", "**", "*.zm"), recursive=True))
    if kept:
        print("\n".join(kept))
        print("lint_lib.py: %d finding(s) across %d files under lib/ (%d suppressed)"
              % (len(kept), files, len(findings) - len(kept)), file=sys.stderr)
        sys.exit(1)
    print("lint_lib.py: no findings across %d files under lib/ (%d suppressed)"
          % (files, len(findings) - len(kept)))


if __name__ == "__main__":
    main()
