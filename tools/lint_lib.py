#!/usr/bin/env python3
"""Runs `ziman --lint` over every module in lib/.

A library module cannot simply be handed to `--lint`: as an entry point its `pub fn`s merge into
the prelude's namespace, so `fs.zm`'s own `lines` collides with the prelude's and the load fails
with "function 'lines' is already defined" before any rule runs. Reached through `use` they are
namespaced and load cleanly, so this generates one throwaway entry that imports all of them.

ZIMAN_MODULE_PATH points at the sources on purpose. Without it the imports resolve to the copies
bundled into the binary, whose declarations carry a NULL `source_file` -- the very flag the lint
uses to tell a user's code from the standard library -- and every finding in lib/ is discarded
before it is printed (docs/reviews/tasks/ F133).

Exits 1 if any finding is reported, 0 otherwise.
"""
import os
import subprocess
import sys
import tempfile

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
DIRS = ["lib/core", "lib/db", "lib/http", "lib/time"]


def main():
    modules = sorted({
        f[:-3]
        for d in DIRS
        for f in os.listdir(os.path.join(ROOT, d))
        if f.endswith(".zm")
    })
    entry = ["// Generated by tools/lint_lib.py -- every library module, so --lint can see them all."]
    entry += ["use %s" % m for m in modules]
    entry += ["", "fn main() {", '    print("lint")', "}"]
    with tempfile.TemporaryDirectory() as tmp:
        path = os.path.join(tmp, "lint_all.zm")
        with open(path, "w") as f:
            f.write("\n".join(entry) + "\n")
        env = dict(os.environ, ZIMAN_MODULE_PATH=":".join(os.path.join(ROOT, d) for d in DIRS))
        done = subprocess.run([os.path.join(ROOT, "ziman"), "--lint", path],
                              env=env, capture_output=True, text=True)
    out = (done.stdout + done.stderr).strip()
    if out:
        print(out)
        print("lint_lib.py: %d finding(s) across %d modules" % (len(out.splitlines()), len(modules)),
              file=sys.stderr)
        sys.exit(1)
    print("lint_lib.py: no findings across %d library modules" % len(modules))


if __name__ == "__main__":
    main()
