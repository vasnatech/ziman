#ifndef ZIMAN_COVERAGE_H
#define ZIMAN_COVERAGE_H

#include "ast.h"

/* `--coverage`: which lines of the user's own code actually ran.
 *
 * The counting is one increment in exec_stmt (interpreter.c) into `Stmt.exec_count`, enabled by
 * ziman_coverage_enable so an ordinary run pays only a branch on a global that is always false.
 * This module does the other half: once the program has finished, walk every statement the parser
 * produced and turn those counts into a per-file report.
 *
 * "Executable line" means exactly "a line some statement starts on". That definition falls out of
 * walking the AST rather than being a second model of the language that could drift from it -- the
 * same walk that finds a statement's line is the one that reads whether it ran. A line carrying
 * several statements counts once and is covered if any of them ran; a `}`, a blank line, and a
 * block's own opening brace are not executable and are never counted against you.
 *
 * Only the user's own code is reported: a function with a NULL `source_file` is a bundled core
 * module or the prelude, and one with `derived_from` set was generated by a `#[derive]`, neither of
 * which the person running the tests wrote. That is the same filter `--lint` already uses
 * (typecheck.c's `g_lint_active`), deliberately, so the two tools agree about whose code it is. */
void ziman_coverage_enable(void);

/* Read directly by exec_stmt's hot path rather than through a function: this build has no LTO, so
 * an accessor would be a real cross-translation-unit call for every statement executed. Write it
 * only through ziman_coverage_enable.
 *
 * Cost of having the counter at all, against a build without the field or the branch: not findable
 * on the machine it was measured on. Fifteen paired rounds of a statement-dense loop (80 million
 * statement executions each) put the two medians within 0.2% of one another, with the 95% interval
 * on the paired difference running -4.4% to +2.6% -- so the honest claim is "below the noise floor",
 * not "zero". Smaller interleaved runs of the same comparison gave +1.6% and -2.0% at different
 * times, which is the useful warning: this is a sub-1% effect and anything measured here with fewer
 * rounds than that is reading noise. */
extern int ziman_coverage_on;

/* Folds one module's statement counts into the running report. Separate from the reporting step
 * because `ziman test` type-checks and runs each file as its own Module: a helper shared by two
 * test files is parsed once per file and so has two distinct ASTs, and the accumulation here keys
 * by source file name, which is what merges them back into one honest answer -- a line is covered
 * if any file's run reached it. */
void ziman_coverage_accumulate(const Module *module);

/* Prints the accumulated report to stdout and returns the number of uncovered executable lines
 * (0 when everything ran). Call once, after every module has been accumulated. */
int ziman_coverage_report(void);

#endif
